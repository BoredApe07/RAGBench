import re
from typing import List, Optional
from pydantic import BaseModel, Field
from google import genai
from google.genai import types

from app.config import settings
from app.retrieval.base import SearchResult


class GenerationResponse(BaseModel):
    """
    Structured output returned by the LLM generation service.
    Contains the answer, extracted citations, source chunks, and model metadata.
    """
    answer: str = Field(..., description="Grounded answer text generated by LLM")
    citations: List[str] = Field(default_factory=list, description="Extracted citation tags found in answer")
    sources_used: List[SearchResult] = Field(default_factory=list, description="Retrieved chunks provided as context")
    model_name: str = Field(..., description="Name of LLM model used")


class GeminiGenerator:
    """
    Citation-backed generator powered by Google Gemini Flash.
    Strictly instructs the LLM to ground its answers and cite source documents.
    """

    SYSTEM_INSTRUCTION = (
        "You are an expert, fact-grounded research assistant.\n"
        "Your task is to answer the user's question using ONLY the provided context snippets below.\n"
        "Rules:\n"
        "1. Strictly base your answer on the provided context snippets. Do NOT assume, speculate, or introduce external knowledge.\n"
        "2. For EVERY factual claim or sentence you write, you MUST cite its source using this exact format: [Doc <id>, Chunk <index>].\n"
        "   Example: 'Retrieval-augmented generation grounds responses in verified facts [Doc 1, Chunk 2].'\n"
        "3. If the provided context does NOT contain enough information to answer the question, clearly state:\n"
        "   'I cannot answer this question based on the provided documents.'\n"
        "4. Be direct, clear, and concise."
    )

    def __init__(self, api_key: Optional[str] = None, model_name: Optional[str] = None):
        self.api_key = api_key or settings.GEMINI_API_KEY
        self.model_name = model_name or settings.GEMINI_MODEL
        # Initialize the official Google GenAI client
        self.client = genai.Client(api_key=self.api_key)

    def build_prompt(self, query: str, contexts: List[SearchResult]) -> str:
        """
        Formats retrieved SearchResult chunks and user query into a grounded prompt.
        """
        context_blocks = []
        for c in contexts:
            header = f"[Doc {c.document_id}, Chunk {c.chunk_index}]"
            context_blocks.append(f"{header}:\n\"{c.content}\"")

        formatted_context = "\n\n".join(context_blocks)

        prompt = (
            f"=== CONTEXT SNIPPETS ===\n"
            f"{formatted_context}\n\n"
            f"=== USER QUESTION ===\n"
            f"{query}\n\n"
            f"=== YOUR GROUNDED ANSWER (WITH CITATIONS) ==="
        )
        return prompt

    @staticmethod
    def extract_citations(text: str) -> List[str]:
        """
        Extracts all citation tags from the text matching Doc X, Chunk Y.
        Supports both [Doc 1, Chunk 2] and grouped [Doc 1, Chunk 0, Doc 1, Chunk 2].
        """
        pattern = r"Doc\s*\d+,\s*Chunk\s*\d+"
        matches = re.findall(pattern, text, re.IGNORECASE)
        # Deduplicate while preserving original order and format with brackets
        seen = set()
        unique_citations = []
        for m in matches:
            formatted = f"[{m.strip()}]"
            if formatted not in seen:
                seen.add(formatted)
                unique_citations.append(formatted)
        return unique_citations

    def generate(
        self,
        query: str,
        contexts: List[SearchResult],
        temperature: float = 0.2
    ) -> GenerationResponse:
        """
        Sends the grounded prompt to Gemini and returns the cited answer.
        """
        prompt = self.build_prompt(query, contexts)

        # Call Gemini using the modern Google GenAI SDK
        response = self.client.models.generate_content(
            model=self.model_name,
            contents=prompt,
            config=types.GenerateContentConfig(
                system_instruction=self.SYSTEM_INSTRUCTION,
                temperature=temperature,  # Low temperature for factual, deterministic answers
            )
        )

        answer_text = response.text or ""
        citations = self.extract_citations(answer_text)

        return GenerationResponse(
            answer=answer_text.strip(),
            citations=citations,
            sources_used=contexts,
            model_name=self.model_name
        )
